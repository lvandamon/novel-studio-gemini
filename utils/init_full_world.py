    for topic, content in rules:
        memory.add_bible_entry("WorldRule", topic, content)

    # --- C. 主角绝对底线 (Character Core / Taboos) ---
    # 这些是 Reviewer 审核的重点，绝不能崩
    memory.add_bible_entry("CharacterCore", "萧风_底线", "绝不滥杀无辜凡人，但对敌人必须斩草除根，绝不留后患。")
