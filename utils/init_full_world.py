    memory = MemoryManager()
    
    # ==============================================================================
    # 1. 世界圣经 (World Bible) - 绝对真理与规则
    # ==============================================================================
    print("📖 [1/4] 录入世界圣经...")

    # --- A. 修炼/战力体系 (Cultivation System) ---
