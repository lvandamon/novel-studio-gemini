    # 上一章摘要 (Ch0 - 背景板)
    memory.update_chapter_summary(0, "萧风本是修真世家少主，家族被灭后流落至青云门。因五灵根资质极差，三年未突破凝气三层，受尽白眼。昨日，他在打扫祖师祠堂时，意外发现一枚刻有'逆'字的黑色戒指，虽然无法认主，但隐约感觉到其中蕴含着恐怖的能量。与此同时，外门恶霸赵虎盯上了他积攒多年的三块灵石。")

    print("\n✅ 世界观初始化完成！现在你可以运行 `uv run streamlit run app.py` 开始创作了。")

